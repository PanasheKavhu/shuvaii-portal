// Generates supabase/tests/16_grade_fixtures.test.sql from seed/*.csv: the
// seed's structure, learners, assessments and marks, and the expected rows
// of seed/expected_subject_results.csv and seed/expected_class_positions.csv,
// so pgTAP can prove public.subject_results() and public.class_positions()
// reproduce both files exactly (D31). pgTAP cannot read the CSVs itself.
//
// Every id is mapped to a new stable uuid, so the test runs (in a rolled
// back transaction) on a database that already holds the seed.
//
//   node scripts/grade-fixture-test.mjs
//
// tests/unit/grading/fixtures.test.ts fails when the file is out of date.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const FIXTURE_TEST_PATH = "supabase/tests/16_grade_fixtures.test.sql";

const ADMIN_ID = "e3000000-0000-0000-0000-000000000001";
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

function parseLine(line) {
  const cells = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      cells.push(cell);
      cell = "";
    } else cell += ch;
  }
  cells.push(cell);
  return cells;
}

function readCsv(root, name) {
  const [header, ...lines] = readFileSync(path.join(root, "seed", `${name}.csv`), "utf8")
    .replace(/^﻿/, "")
    .split(/\r?\n/)
    .filter((l) => l.trim() !== "");
  const columns = parseLine(header);
  return lines.map((line) => {
    const cells = parseLine(line);
    return Object.fromEntries(columns.map((c, i) => [c, cells[i] ?? ""]));
  });
}

/** A new uuid for a seed id, the same every run. */
function remap(id) {
  const hex = createHash("sha1").update(`grade-fixture:${id}`).digest("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

function literal(value) {
  if (value === null || value === "") return "null";
  if (UUID.test(value)) return `'${remap(value)}'`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insert(table, columns, rows, valuesOf) {
  const lines = rows.map((row) => `  (${valuesOf(row).map(literal).join(", ")})`);
  return `insert into public.${table} (${columns.join(", ")}) values\n${lines.join(",\n")};\n`;
}

function pick(...columns) {
  return [columns, (row) => columns.map((c) => row[c])];
}

export function buildFixtureTest(root) {
  const csv = (name) => readCsv(root, name);
  const schools = csv("schools");
  const out = [];

  out.push(`-- GENERATED by scripts/grade-fixture-test.mjs from seed/*.csv. Do not edit;
-- run \`node scripts/grade-fixture-test.mjs\` after changing the seed.
--
-- pgTAP: public.subject_results() and public.class_positions() reproduce
-- seed/expected_subject_results.csv and seed/expected_class_positions.csv
-- exactly, every row, including the absences and the tie (D31). The seed's
-- ids are mapped to new ones so this runs beside a seeded database. Class
-- teachers and subject teachers are left empty; a school admin of both
-- schools reads the results.
begin;

select plan(6);
`);

  out.push(`insert into auth.users (
  id, instance_id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change
)
values ('${ADMIN_ID}', '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated',
        'admin@grade-fixture.test', '', now(), '{}', '{}', now(), now(), '', '', '', '');
`);

  out.push(
    insert("schools", ["id", "slug", "name", "stage", "timezone", "status"], schools, (s) => [
      s.id,
      `${s.slug}-grade-fixture`,
      s.name,
      s.stage,
      s.timezone,
      s.status,
    ]),
  );
  out.push(
    `insert into public.memberships (school_id, user_id, role, status) values\n${schools
      .map((s) => `  (${literal(s.id)}, '${ADMIN_ID}', 'school_admin', 'active')`)
      .join(",\n")};\n`,
  );

  const tables = [
    ["grading_scales", pick("id", "school_id", "name", "stage")],
    ["grade_levels", pick("id", "school_id", "name", "stage", "sort_order", "grading_scale_id")],
    [
      "grading_bands",
      pick("id", "school_id", "scale_id", "grade", "min_mark", "max_mark", "remark", "sort_order"),
    ],
    ["academic_years", pick("id", "school_id", "label", "starts_on", "ends_on")],
    [
      "terms",
      pick(
        "id",
        "school_id",
        "academic_year_id",
        "name",
        "kind",
        "starts_on",
        "ends_on",
        "marks_deadline",
        "status",
      ),
    ],
    ["classes", pick("id", "school_id", "academic_year_id", "grade_level_id", "name")],
    ["subjects", pick("id", "school_id", "code", "name", "stage_scope", "is_core", "sort_order")],
    ["class_subjects", pick("id", "school_id", "class_id", "subject_id")],
    [
      "learners",
      [
        ["id", "school_id", "learner_number", "first_name", "last_name"],
        (l) => [l.id, l.school_id, l.learner_number, "Learner", l.learner_number],
      ],
    ],
    ["enrolments", pick("id", "school_id", "learner_id", "class_id", "academic_year_id", "status")],
    ["enrolment_subjects", pick("id", "school_id", "enrolment_id", "class_subject_id")],
    [
      "assessments",
      pick(
        "id",
        "school_id",
        "term_id",
        "class_subject_id",
        "name",
        "type",
        "max_mark",
        "weight_percent",
        "sort_order",
      ),
    ],
    ["marks", pick("id", "school_id", "assessment_id", "enrolment_id", "score", "status")],
  ];
  for (const [name, [columns, valuesOf]] of tables) {
    out.push(`\n-- ${name}\n`);
    out.push(insert(name, columns, csv(name), valuesOf));
  }

  out.push(`
create temp table expected_subject_results (
  term_id uuid, class_id uuid, enrolment_id uuid, class_subject_id uuid,
  weighted_percent numeric, rounded_mark int, grade text, result_status text
) on commit drop;
`);
  out.push(
    insert(
      "expected_subject_results",
      [
        "term_id",
        "class_id",
        "enrolment_id",
        "class_subject_id",
        "weighted_percent",
        "rounded_mark",
        "grade",
        "result_status",
      ],
      csv("expected_subject_results"),
      (r) => [
        r.term_id,
        r.class_id,
        r.enrolment_id,
        r.class_subject_id,
        r.weighted_percent,
        r.rounded_mark,
        r.grade,
        r.result_status,
      ],
    ).replace("public.expected_subject_results", "expected_subject_results"),
  );
  out.push(`
create temp table expected_class_positions (
  term_id uuid, class_id uuid, enrolment_id uuid, subjects_counted int,
  average numeric, "position" int, class_size int
) on commit drop;
`);
  out.push(
    insert(
      "expected_class_positions",
      [
        "term_id",
        "class_id",
        "enrolment_id",
        "subjects_counted",
        "average",
        '"position"',
        "class_size",
      ],
      csv("expected_class_positions"),
      (r) => [
        r.term_id,
        r.class_id,
        r.enrolment_id,
        r.subjects_counted,
        r.average,
        r.position,
        r.class_size,
      ],
    ).replace("public.expected_class_positions", "expected_class_positions"),
  );

  const schoolList = schools.map((s) => literal(s.id)).join(", ");
  out.push(`
-- Every class with every term of its year, read as the school admin.
create temp table fixture_class_terms on commit drop as
select c.id as class_id, t.id as term_id, t.kind
from public.classes c
join public.terms t on t.academic_year_id = c.academic_year_id
where c.school_id in (${schoolList});

select set_config('request.jwt.claim.sub', '${ADMIN_ID}', true);

select is((select count(*) from expected_subject_results), 486::bigint, 'the fixture has 486 subject results');

select bag_eq(
  $$ select r.term_id, r.class_id, r.enrolment_id, r.class_subject_id, r.weighted_percent,
            r.rounded_mark, r.grade, r.result_status
     from fixture_class_terms ct
     cross join lateral public.subject_results(ct.class_id, ct.term_id) r $$,
  $$ select * from expected_subject_results $$,
  'subject results reproduce seed/expected_subject_results.csv exactly'
);

select is(
  (select count(*) from fixture_class_terms ct
   cross join lateral public.subject_results(ct.class_id, ct.term_id) r
   where r.result_status = 'incomplete' and r.incomplete_reason = 'absent'),
  8::bigint,
  'the 8 absences make 8 incomplete subjects'
);

select is((select count(*) from expected_class_positions), 60::bigint, 'the fixture has 60 positions');

select bag_eq(
  $$ select p.term_id, p.class_id, p.enrolment_id, p.subjects_counted, p.average, p."position", p.class_size
     from fixture_class_terms ct
     cross join lateral public.class_positions(ct.class_id, ct.term_id) p
     where ct.term_id in (select term_id from expected_class_positions) $$,
  $$ select * from expected_class_positions $$,
  'averages and positions reproduce seed/expected_class_positions.csv exactly, including the tie'
);

select is(
  (select count(p."position") from fixture_class_terms ct
   cross join lateral public.class_positions(ct.class_id, ct.term_id) p
   where ct.kind = 'vacation'),
  0::bigint,
  'the vacation school has no positions'
);

select * from finish();
rollback;
`);
  return out.join("");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  writeFileSync(path.join(root, FIXTURE_TEST_PATH), buildFixtureTest(root));
  console.log(`Wrote ${FIXTURE_TEST_PATH}`);
}
